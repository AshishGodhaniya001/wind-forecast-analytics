"""FastAPI application entry point.

The application serves two things:

* ``GET /api/health`` - a liveness check that returns no data.
* the read-only analysis endpoints under ``/api/analysis`` - a typed view over
  the January 2026 artefacts generated by ``scripts/analyse_january_data.py``.

Elexon is never called while serving a request. Data retrieval and analysis are
offline steps; this process only reads their outputs.
"""

from __future__ import annotations

import os
from datetime import datetime, timezone

from fastapi import FastAPI
from fastapi.middleware.cors import CORSMiddleware

from app import __version__
from app.api.analysis import router as analysis_router

APP_NAME = "Wind Forecast Analytics API"

# Frontend origins allowed to call this API. Comma-separated, configured
# through the environment so local development and deployment differ only
# by configuration, not by code.
DEFAULT_CORS_ORIGINS = "http://localhost:5173"


def _allowed_origins() -> list[str]:
    raw = os.getenv("CORS_ORIGINS", DEFAULT_CORS_ORIGINS)
    return [origin.strip() for origin in raw.split(",") if origin.strip()]


app = FastAPI(
    title=APP_NAME,
    version=__version__,
    summary="Forecast accuracy analysis for UK national wind generation.",
    description=(
        "Backend for comparing Elexon FUELHH wind generation actuals against "
        "Elexon WINDFOR wind generation forecasts for January 2026. "
        "Analysis endpoints serve pre-generated, validated artefacts; they do "
        "not call Elexon and do not recompute metrics."
    ),
)

app.add_middleware(
    CORSMiddleware,
    allow_origins=_allowed_origins(),
    allow_credentials=False,
    allow_methods=["GET"],
    allow_headers=["*"],
)

app.include_router(analysis_router)


@app.get("/api/health", tags=["system"])
def health() -> dict[str, str]:
    """Report that the API process is running.

    This is a liveness check only. It intentionally returns no data,
    no metrics and no analysis results.
    """
    return {
        "status": "ok",
        "service": APP_NAME,
        "version": __version__,
        "timestamp": datetime.now(timezone.utc).isoformat(),
    }
